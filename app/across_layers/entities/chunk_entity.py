from dataclasses import dataclass


@dataclass(frozen=True)
class ChunkEntity:
    """Фрагмент документа, готовый к записи в векторное хранилище.

    Контракт метаданных чанка (payload в Qdrant): эти поля решены на этапе 2
    осознанно — менять их дорого (миграция коллекции), поэтому здесь только
    то, что нужно пайплайну RAG с самого начала.
    """

    doc_id: str
    # Порядковый номер чанка внутри документа; начинается с 0.
    # На этапе 2 документ = одна строка = один чанк с индексом 0;
    # чанкер на этапе 3-4 будет нарезать документы на много чанков.
    chunk_index: int
    # Источник: имя файла/заголовок, откуда взят чанк (для цитирования в ответе)
    source: str
    content: str

from typing import Protocol

from app.across_layers.entities.user_entity import UserEntity
from app.data_access_layer.models.user_model import UserModel


class UserRepositoryProtocol(Protocol):
    def get_user_by_id(self, user_id: int) -> UserEntity | None: ...
    def get_user_by_email(self, email: str) -> UserEntity | None: ...
    def get_user_model_by_email(self, email: str) -> UserModel | None: ...
    def create_user(self, username: str, email: str, password: str) -> UserEntity: ...
    def delete_user(self, user_id: int) -> bool: ...
    def update_user(self, user_id: int, username: str | None = None, email: str | None = None) -> UserEntity | None: ...
